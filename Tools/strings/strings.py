#!/usr/bin/env python3
"""Writes the shells' strings from Localization/strings.json.

  Apple     Packages/Sources/WTUI/Resources/Localizable.xcstrings
  Android   Android/app/src/main/res/values/strings.xml, and values-<language>/strings.xml
            for each other language. The key error.net.dns is the resource error_net_dns.

The output is checked in. With --check nothing is written and the script fails
when a checked-in file is stale (Tools/test.sh lint runs it).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Localization" / "strings.json"
CATALOG = ROOT / "Packages" / "Sources" / "WTUI" / "Resources" / "Localizable.xcstrings"
ANDROID_RES = ROOT / "Android" / "app" / "src" / "main" / "res"
ANDROID_HEADER = "<!-- Generated by Tools/strings/strings.py from Localization/strings.json. Do not edit. -->"
KEY = re.compile(r"^[a-z0-9_]+(\.[a-z0-9_]+)+$")
# A printf placeholder as the source writes it, Apple's way: %@, %d, %ld, %1$@, and %% for a
# literal per cent sign.
PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(%|@|s|l{0,2}[du]|f)")


def catalog(strings: dict) -> str:
    entries = {}
    for key in sorted(strings):
        entry = strings[key]
        if not KEY.match(key):
            raise SystemExit(f"{key!r} is not a dotted lower-case key")
        if "en" not in entry or "note" not in entry:
            raise SystemExit(f"{key!r} needs both 'en' and 'note'")
        localizations = {
            language: {"stringUnit": {"state": "translated", "value": value}}
            for language, value in sorted(entry.items())
            if language != "note"
        }
        entries[key] = {
            "comment": entry["note"],
            "extractionState": "manual",
            "localizations": localizations,
        }
    document = {"sourceLanguage": "en", "strings": entries, "version": "1.0"}
    return json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def android_placeholders(key: str, value: str) -> str:
    """Apple's placeholders as Android's: %@ is %s, %ld is %d. Android wants a string with
    more than one placeholder to number them, so those that are not numbered are."""
    found = [match for match in PLACEHOLDER.finditer(value) if match.group(2) != "%"]
    if "%" in PLACEHOLDER.sub("", value):
        raise SystemExit(f"{key!r} has a '%' that is not a placeholder; write a literal one as '%%'")
    numbered = [match for match in found if match.group(1)]
    if numbered and len(numbered) != len(found):
        raise SystemExit(f"{key!r} numbers some of its placeholders and not others")
    number_them = len(found) > 1 and not numbered
    count = 0

    def convert(match: re.Match) -> str:
        nonlocal count
        position, kind = match.group(1), match.group(2)
        if kind == "%":
            return "%%"
        count += 1
        if number_them:
            position = str(count)
        kind = "s" if kind in "@s" else "f" if kind == "f" else "d"
        return f"%{position}${kind}" if position else f"%{kind}"

    return PLACEHOLDER.sub(convert, value)


def android_text(key: str, value: str) -> str:
    """A string as the text of a <string> element: aapt's escapes, then XML's."""
    text = android_placeholders(key, value)
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    text = text.replace("\n", "\\n").replace("\t", "\\t")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    # aapt trims a string and collapses its runs of spaces unless it is quoted.
    if text != text.strip(" ") or "  " in text:
        text = f'"{text}"'
    return text


def android_folder(language: str) -> str:
    """The resource folder for a BCP 47 language: values for the source language, values-fr,
    values-pt-rBR, and values-b+sr+Latn for anything longer."""
    if language == "en":
        return "values"
    parts = language.split("-")
    if not all(part.isalnum() for part in parts):
        raise SystemExit(f"{language!r} is not a language tag")
    if len(parts) == 1:
        return f"values-{parts[0].lower()}"
    if len(parts) == 2 and len(parts[1]) == 2 and parts[1].isalpha():
        return f"values-{parts[0].lower()}-r{parts[1].upper()}"
    return "values-b+" + "+".join(parts)


def android(strings: dict) -> dict:
    """Every strings.xml, by path."""
    names = {}
    for key in sorted(strings):
        name = key.replace(".", "_")
        if name[0].isdigit():
            raise SystemExit(f"{key!r} starts with a digit: it cannot name an Android resource")
        if name in names:
            raise SystemExit(f"{key!r} and {names[name]!r} are the same Android resource, {name}")
        names[name] = key
    languages = sorted({language for entry in strings.values() for language in entry if language != "note"})
    files = {}
    for language in languages:
        out = ['<?xml version="1.0" encoding="utf-8"?>', ANDROID_HEADER, "<resources>"]
        for name, key in names.items():
            entry = strings[key]
            if language not in entry:
                continue
            if language == "en":
                # A comment may not hold two hyphens in a row.
                out.append(f"    <!-- {re.sub('-{2,}', '-', entry['note']).strip()} -->")
            out.append(f'    <string name="{name}">{android_text(key, entry[language])}</string>')
        out += ["</resources>", ""]
        files[ANDROID_RES / android_folder(language) / "strings.xml"] = "\n".join(out)
    return files


def android_leftovers(wanted: dict) -> list:
    """Generated strings.xml files for languages the source no longer has."""
    return [
        path
        for path in sorted(ANDROID_RES.glob("values*/strings.xml"))
        if path not in wanted and ANDROID_HEADER in path.read_text(encoding="utf-8")
    ]


def main() -> int:
    strings = json.loads(SOURCE.read_text(encoding="utf-8"))["strings"]
    wanted = {CATALOG: catalog(strings), **android(strings)}
    leftovers = android_leftovers(wanted)
    if "--check" in sys.argv[1:]:
        stale = [path for path, text in wanted.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale or leftovers:
            for path in stale + leftovers:
                print(f"Stale: {path.relative_to(ROOT)}", file=sys.stderr)
            print("Strings are stale; run Tools/strings/strings.py", file=sys.stderr)
            return 1
        print("Strings are up to date.")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    for path in leftovers:
        path.unlink()
        print(f"Removed {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
