#!/usr/bin/env python3
"""Writes the shells' design tokens from Design/tokens.json.

  Swift    Packages/Sources/WTDesign/Tokens.generated.swift
  Kotlin   Android/app/src/main/kotlin/com/tigercodes/webtiger/design/Tokens.kt

The output is checked in. With --check nothing is written and the script fails
when a checked-in file is stale (Tools/test.sh lint runs it).
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Design" / "tokens.json"
SWIFT = ROOT / "Packages" / "Sources" / "WTDesign" / "Tokens.generated.swift"
KOTLIN = ROOT / "Android" / "app" / "src" / "main" / "kotlin" / "com" / "tigercodes" / "webtiger" / "design" / "Tokens.kt"


def rgba(text: str) -> str:
    """#RRGGBB or #RRGGBBAA as 0xRRGGBBAA."""
    digits = text.lstrip("#")
    if len(digits) == 6:
        digits += "FF"
    if len(digits) != 8 or any(c not in "0123456789abcdefABCDEF" for c in digits):
        raise SystemExit(f"{text!r} is not #RRGGBB or #RRGGBBAA")
    return "0x" + digits.upper()


def swift(tokens: dict) -> str:
    out = [
        "// Generated by Tools/design/tokens.py from Design/tokens.json. Do not edit.",
        "public import SwiftUI",
        "",
        "/// WebTiger's design tokens.",
        "public enum Tokens {",
        "    public enum Palette {",
    ]
    for name, pair in tokens["color"].items():
        out.append(
            f"        public static let {name} = Color(light: {rgba(pair['light'])}, dark: {rgba(pair['dark'])})"
        )
    out.append("    }")
    for group in ("space", "radius", "size"):
        out += ["", f"    public enum {group.capitalize()} {{"]
        for name, value in tokens[group].items():
            out.append(f"        public static let {name}: CGFloat = {value}")
        out.append("    }")
    out += ["}", ""]
    return "\n".join(out)


def argb(text: str) -> str:
    """#RRGGBB or #RRGGBBAA as 0xAARRGGBB, which is how Compose writes a colour."""
    digits = rgba(text)[2:]
    return "0x" + digits[6:] + digits[:6]


def kotlin(tokens: dict) -> str:
    out = [
        "// Generated by Tools/design/tokens.py from Design/tokens.json. Do not edit.",
        "package com.tigercodes.webtiger.design",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "",
        "/** WebTiger's design tokens. */",
        "object Tokens {",
        "    object Palette {",
    ]
    for name, pair in tokens["color"].items():
        out.append(
            f"        val {name} = TokenColor(light = Color({argb(pair['light'])}), dark = Color({argb(pair['dark'])}))"
        )
    out.append("    }")
    for group in ("space", "radius", "size"):
        out += ["", f"    object {group.capitalize()} {{"]
        for name, value in tokens[group].items():
            out.append(f"        val {name} = {value}.dp")
        out.append("    }")
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    wanted = {SWIFT: swift(tokens), KOTLIN: kotlin(tokens)}
    if "--check" in sys.argv[1:]:
        stale = [path for path, text in wanted.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale:
            for path in stale:
                print(f"Stale: {path.relative_to(ROOT)}", file=sys.stderr)
            print("Design tokens are stale; run Tools/design/tokens.py", file=sys.stderr)
            return 1
        print("Design tokens are up to date.")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
